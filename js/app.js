function setupStudioZoom() {
  const container = document.getElementById('studioZoomContainer');
  const targetImg = document.getElementById('zoomTargetImg');
  const loupe = document.getElementById('loupeGlass');
  const thumbs = document.querySelectorAll('.zoom-angle-thumb');

  if (!container || !targetImg || !loupe) return;

  const zoomLevel = 2.5;

  const updateLoupeBackground = () => {
    loupe.style.backgroundImage = 'url("' + targetImg.src + '")';
    loupe.style.backgroundSize = (targetImg.width * zoomLevel) + 'px ' + (targetImg.height * zoomLevel) + 'px';
  };

  if (targetImg.complete) {
    updateLoupeBackground();
  } else {
    targetImg.onload = updateLoupeBackground;
  }

  container.addEventListener('mouseenter', () => {
    loupe.style.display = 'block';
    updateLoupeBackground();
  });

  container.addEventListener('mouseleave', () => {
    loupe.style.display = 'none';
  });

  container.addEventListener('mousemove', (e) => {
    const rect = container.getBoundingClientRect();
    const imgRect = targetImg.getBoundingClientRect();

    let x = e.clientX - rect.left;
    let y = e.clientY - rect.top;

    loupe.style.left = (x - loupe.offsetWidth / 2) + 'px';
    loupe.style.top = (y - loupe.offsetHeight / 2) + 'px';

    const imgX = e.clientX - imgRect.left;
    const imgY = e.clientY - imgRect.top;

    const bgX = -(imgX * zoomLevel - loupe.offsetWidth / 2);
    const bgY = -(imgY * zoomLevel - loupe.offsetHeight / 2);

    loupe.style.backgroundPosition = bgX + 'px ' + bgY + 'px';
  });

  thumbs.forEach(thumb => {
    thumb.addEventListener('click', () => {
      thumbs.forEach(t => t.classList.remove('active'));
      thumb.classList.add('active');
      const newSrc = thumb.getAttribute('data-src');
      if (newSrc && targetImg) {
        targetImg.src = newSrc;
        setTimeout(updateLoupeBackground, 100);
      }
    });
  });
}

