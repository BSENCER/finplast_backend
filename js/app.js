// Navigation & Header Scroll (Full Mobile Support)
function setupNavigation() {
  const header = document.getElementById('siteHeader');
  const mobileToggle = document.getElementById('mobileNavToggle');
  const mainNav = document.getElementById('mainNav');
  const dropdownTriggers = document.querySelectorAll('.dropdown-trigger');

  // Sticky header on scroll
  window.addEventListener('scroll', () => {
    if (header) {
      header.classList.toggle('scrolled', window.scrollY > 30);
    }
  }, { passive: true });

  // ── Mobile drawer open/close ──
  function openNav() {
    mainNav && mainNav.classList.add('open');
    document.body.classList.add('nav-open');
    if (mobileToggle) mobileToggle.setAttribute('aria-expanded', 'true');
  }

  function closeNav() {
    mainNav && mainNav.classList.remove('open');
    document.body.classList.remove('nav-open');
    if (mobileToggle) mobileToggle.setAttribute('aria-expanded', 'false');
  }

  if (mobileToggle) {
    mobileToggle.addEventListener('click', () => {
      const isOpen = mainNav && mainNav.classList.contains('open');
      isOpen ? closeNav() : openNav();
    });
  }

  const mobileCloseBtn = document.getElementById('mobileNavCloseBtn');
  if (mobileCloseBtn) {
    mobileCloseBtn.addEventListener('click', closeNav);
  }

  const mobileDrawerCtaBtn = document.getElementById('mobileDrawerCtaBtn');
  if (mobileDrawerCtaBtn) {
    mobileDrawerCtaBtn.addEventListener('click', closeNav);
  }

  // Close drawer when clicking the overlay
  document.body.addEventListener('click', (e) => {
    if (document.body.classList.contains('nav-open')) {
      // Click outside the nav drawer
      if (mainNav && !mainNav.contains(e.target) && e.target !== mobileToggle && !mobileToggle.contains(e.target)) {
        closeNav();
      }
    }
  });

  // Close on ESC
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeNav();
  });

  // Close on any nav link click (except dropdown triggers on mobile)
  document.querySelectorAll('.dropdown-item, .nav-link:not(.dropdown-trigger)').forEach(link => {
    link.addEventListener('click', () => closeNav());
  });

  // Dropdown toggle on click (both desktop & mobile)
  dropdownTriggers.forEach(trigger => {
    trigger.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      const parent = trigger.closest('.has-dropdown');
      if (!parent) return;

      const isMobile = window.innerWidth <= 860;
      const targetClass = isMobile ? 'mobile-open' : 'is-open';
      const wasOpen = parent.classList.contains(targetClass);

      // Close all dropdowns
      document.querySelectorAll('.has-dropdown').forEach(el => {
        el.classList.remove('is-open', 'mobile-open');
        const t = el.querySelector('.dropdown-trigger');
        if (t) t.setAttribute('aria-expanded', 'false');
      });

      if (!wasOpen) {
        parent.classList.add(targetClass);
        trigger.setAttribute('aria-expanded', 'true');
      }
    });
  });

  // Close dropdown on outside click
  document.addEventListener('click', (e) => {
    if (!e.target.closest('.has-dropdown')) {
      document.querySelectorAll('.has-dropdown').forEach(el => {
        el.classList.remove('is-open', 'mobile-open');
        const t = el.querySelector('.dropdown-trigger');
        if (t) t.setAttribute('aria-expanded', 'false');
      });
    }
  });

  // Close dropdown when item clicked
  document.querySelectorAll('.dropdown-item').forEach(link => {
    link.addEventListener('click', () => {
      document.querySelectorAll('.has-dropdown').forEach(el => {
        el.classList.remove('is-open', 'mobile-open');
      });
      closeNav();
    });
  });

  // On window resize: if going wide, reset mobile state
  window.addEventListener('resize', () => {
    if (window.innerWidth > 860) {
      closeNav();
      document.querySelectorAll('.has-dropdown.mobile-open').forEach(el => el.classList.remove('mobile-open'));
    }
  });
}

// Language Switcher
function setupLanguageSwitcher() {
  const langBtns = document.querySelectorAll('.lang-btn');
  langBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      if (lang && translations[lang]) {
        currentLang = lang;
        if (window.FinplastAPI) window.FinplastAPI.setLanguage(lang);
        langBtns.forEach(b => b.classList.toggle('active', b.getAttribute('data-lang') === lang));
        applyTranslations(lang);
        renderWorkflow();
        if (window.FinplastAPI) window.FinplastAPI.navigation('header').then(applyRemoteNavigation).catch(() => {});
      }
    });
  });
}

function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;

  document.querySelectorAll('[data-t]').forEach(el => {
    const key = el.getAttribute('data-t');
    if (t[key]) {
      el.innerHTML = t[key];
    }
  });

  const searchInput = document.getElementById('catalogSearch');
  if (searchInput) {
    if (lang === 'ru') {
      searchInput.placeholder = "Поиск продукции или упаковки... (Напр: Finplast Дой-пак, Стретч, Картридж)";
    } else if (lang === 'en') {
      searchInput.placeholder = "Search products or packaging... (e.g., Finplast Doypack, Stretch, Cartridge)";
    } else {
      searchInput.placeholder = "Məhsul və ya qablaşdırma axtar... (Məs: Finplast Doypack, Streç, Lülə, Şrink)";
    }
  }

  const activeTab = document.querySelector('.catalog-tab.active');
  const currentCat = activeTab ? activeTab.getAttribute('data-cat') : 'all';
  const query = searchInput ? searchInput.value.trim() : '';
  renderCatalog(currentCat, query);
}
